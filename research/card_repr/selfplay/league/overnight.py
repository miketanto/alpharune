# ------------------------------------------------------------------------------------------------ pruning
def prune(a, P, log):
    """Keep at most --max-ckpts league snapshot files; exploiter snapshots go first (newest 2 kept), then the
    oldest main snapshots that are not protected (first / best / previous rated, newest 3, not yet rated)."""
    from registry import Registry
    reg = Registry(P['reg'])
    tl = read_csv(P['tl'])
    rated = [r['member'] for r in tl if r['member'].startswith(P['main_run'])]
    prot = set(rated[:1] + rated[-2:])
    if tl:
        best = max((r for r in tl if r['member'].startswith(P['main_run'])), key=lambda r: float(r['elo'] or -1e9),
                   default=None)
        if best:
            prot.add(best['member'])
    live = [e for e in reg.members(kind='net', loadable=True) if e['run'] in (P['main_run'], P['exp_run'])
            and os.path.exists(reg.abspath(e['id']))]
    mains = sorted([e for e in live if e['run'] == P['main_run']], key=lambda e: e['update'])
    exps = sorted([e for e in live if e['run'] == P['exp_run']], key=lambda e: e['update'])
    last_rated_upd = max([int(r['update']) for r in tl if r['member'].startswith(P['main_run'])] or [0])
    prot |= {e['id'] for e in mains[-3:]} | {e['id'] for e in mains if e['update'] > last_rated_upd}
    prot |= {e['id'] for e in exps[-2:]}
    n = len(live)
    victims = [e for e in exps if e['id'] not in prot] + [e for e in mains if e['id'] not in prot]
    gone = []
    while n > a.max_ckpts and victims:
        e = victims.pop(0)
        try:
            os.remove(reg.abspath(e['id']))
        except OSError:
            pass
        e.update(loadable=False, why='pruned (overnight.py disk cap)', pruned=True)
        gone.append(e['id'])
        n -= 1
    if gone:
        reg.save()
        log(f'pruned {len(gone)} checkpoints: {gone}; {n} left')
    return n


