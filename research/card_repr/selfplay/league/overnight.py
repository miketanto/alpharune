class Multi:
    def __init__(self, paths_):
        from ratings import ResultStore
        self.stores = [ResultStore(p) for p in paths_]

    def load(self):
        out = []
        for s in self.stores:
            out += s.load()
        return out

    def matrix(self, names=None):
        from ratings import ResultStore
        st = ResultStore('/nonexistent')
        st.load = self.load
        return st.matrix(names)


def wr_of(recs, a, b):
    w = g = 0.0
    for r in recs:
        if r['a'] == a and r['b'] == b:
            w += r['a_wins'] + 0.5 * r.get('draws', 0); g += r['games']
        elif r['a'] == b and r['b'] == a:
            w += r['b_wins'] + 0.5 * r.get('draws', 0); g += r['games']
    return round(w / g, 3) if g else ''


def fit_all(P):
    from ratings import fit_bt
    ms = Multi([DEMO_RESULTS, P['res']])
    names, W, N = ms.matrix()
    return fit_bt(names, W, N, anchor='anchor:random-player', prior_games=1.0), ms


def rate(a):
    """One rating cycle for a.member (run by the driver in the background at nice 10 on cores 12-15)."""
    from match import play
    from ratings import ResultStore, ratings_table
    from registry import Registry
    P = paths(a)
    log = Log(P['log'])
    reg = Registry(P['reg'])
    st = ResultStore(P['res'])
    t0 = time.time()
    n = a.rate_games
    anchors = [A100, A200] if not a.no_ismcts else []

    def have(x, y):
        return st.pair_games().get(tuple(sorted((x, y))), 0)

    def game(x, y, games=n):
        if have(x, y) >= games:
            return
        try:
            rec = play(reg, x, y, games - have(x, y), procs=a.rate_procs)
            st.append(rec)
            log(f'  rate {x} vs {y}: {rec["a_wins"]}-{rec["b_wins"]} ({rec["secs"]}s)')
        except Exception as e:
            log(f'  ERROR rate {x} vs {y}: {e!r}')

    tl = read_csv(P['tl'])
    if not any(r['member'] == BASE_B2 for r in tl):          # baselines once: tie cf_B2 / cf_id into the demo scale
        log('rating baselines (once): cf_B2@230, cf_id@230')
        for b in (BASE_B2, BASE_ID):
            for y in anchors + list(LINK):
                game(b, y)
        game(BASE_B2, BASE_ID)
        write_row(P, log, BASE_B2, 0, None, None, None, None, t0)
        tl = read_csv(P['tl'])
    m = a.member
    if m == BASE_B2:          # the start point is rated by the baseline block above
        return
    mains = [r for r in tl if r['member'].startswith(P['main_run'] + '@')]
    first = mains[0]['member'] if mains else None
    prev = mains[-1]['member'] if mains else BASE_B2
    best = None
    if mains:
        fit, _ = fit_all(P)
        cand = [r['member'] for r in mains if r['member'] in fit['elo'] and reg.m.get(r['member'], {}).get('loadable')]
        best = max(cand, key=lambda k: fit['elo'][k], default=None)
    exps = sorted([e for e in reg.members(kind='net', loadable=True) if e['run'] == P['exp_run']
                   and os.path.exists(reg.abspath(e['id']))], key=lambda e: e['update'])
    expl = exps[-1]['id'] if exps else None
    opps = []
    for y in anchors + [BASE_B2, BASE_ID, first, prev, best, expl]:
        if y and y != m and y not in opps and y in reg.m and reg.m[y].get('loadable'):
            opps.append(y)
    log(f'rating cycle {m}: vs {opps}')
    for y in opps:
        game(m, y)
    write_row(P, log, m, reg.m[m]['update'], prev, first, best, expl, t0)


def write_row(P, log, m, upd, prev, first, best, expl, t0):
    fit, ms = fit_all(P)
    recs = ms.load()
    from ratings import ratings_table
    row = dict(time=time.strftime('%Y-%m-%dT%H:%M:%S'), update=upd, member=m,
               elo=round(fit['elo'].get(m, float('nan')), 1), ci_lo=round(fit['lo'].get(m, float('nan')), 1),
               ci_hi=round(fit['hi'].get(m, float('nan')), 1), wr_ismcts200=wr_of(recs, m, A200),
               wr_ismcts100=wr_of(recs, m, A100), wr_cf_B2=wr_of(recs, m, BASE_B2) if m != BASE_B2 else 0.5,
               wr_cf_id=wr_of(recs, m, BASE_ID), wr_prev=wr_of(recs, m, prev) if prev and prev != m else '',
               prev=prev or '', wr_first=wr_of(recs, m, first) if first else '', first=first or '',
               wr_best=wr_of(recs, m, best) if best else '', best=best or '',
               wr_vs_exploiter=wr_of(recs, m, expl) if expl else '', exploiter=expl or '',
               games=sum(r['games'] for r in recs if m in (r['a'], r['b'])), secs=round(time.time() - t0))
    append_csv(P['tl'], TL_COLS, row)
    with open(P['ratings'], 'w') as f:
        f.write(f'refit {time.ctime()} (demo + overnight results; random-player = 0)\n' + ratings_table(fit) + '\n')
    log(f'timeline: {m} Elo {row["elo"]} [{row["ci_lo"]}, {row["ci_hi"]}] wr vs ismcts200 {row["wr_ismcts200"]} '
        f'vs cf_B2 {row["wr_cf_B2"]} vs prev {row["wr_prev"]} ({row["secs"]}s)')


