"""Unattended overnight league training for the Rengar mirror (league/README.txt section 9).

  python3 league/overnight.py run --deadline 07:30                 # the real run (foreground; exits at the deadline)
  python3 league/overnight.py run --deadline 23:05 --tag dry ...   # dry run (see --help for the small settings)
  python3 league/overnight.py summary [--out league/overnight]     # rewrite SUMMARY.txt from what is on disk
  python3 league/overnight.py rate --out ... --member ID           # one rating cycle (the driver runs this itself)

One GPU process at a time. The driver alternates two trainer processes (learner/selfplay.py --league ...):
  * MAIN agent  runs/<tag>_main: starts from runs/cf_B2/latest.pt (B2, schema v4, --ask-head --ask-opt, opt_refs
    detected from the checkpoint). Opponents: OSFPMix (opponents.py) = 0.8 x OSFP over its OWN history (paper
    settings: p_self 0.6, optimism 1, xi 0.55, max_periods 6, learning period 163,840 decisions = 10 updates;
    history seeded with cf_B2@230) + 0.2 x PFSP (1-p)^2 over the league (main-exploiter snapshots, picked up from
    the registry as they appear, + fixed nets cf_id@230, gate4_B2@150, gate4_id@150).
    Overall: 48% self-play, 32% own history (OSFP), 20% league (PFSP).
    Counterfactual-pair training is OFF (no --cf-data): the CF data were generated by an older policy.
    A periodic snapshot every --snapshot-every updates is registered (role main) for the ratings; only snapshots
    OSFP admits join the OSFP history.
  * MAIN EXPLOITER runs/<tag>_exp: trains only vs a frozen copy of the main agent (<out>/exp_target.pt, re-copied
    from the main's latest.pt before every exploiter phase); exploiter.py rules: snapshot (role main-exploiter,
    joins the league -> the main agent's PFSP pool) when it beats the target >= 70% over >= 200 games or after
    60 updates since its last reset; then reset (prob 1.0) to cf_B2@230 with a fresh optimizer.
  Phases: --main-updates (40) main, then --exp-updates (20) exploiter, repeated.
Rating cycles (background, CPU cores 12-15, nice 10) every --rate-every-min minutes: the newest main snapshot plays
--rate-games games vs ismcts:sims=100, ismcts:sims=200, the first / previous / best rated main snapshots, cf_B2@230,
cf_id@230 and the newest exploiter snapshot; Bradley-Terry refit (random-player = 0) over these results PLUS the
demo results (league/results_demo.jsonl) so the scale matches ratings_demo.txt.
Outputs in <out>: log.txt, elo_timeline.csv, throughput.csv, registry.json, results.jsonl, ratings_latest.txt,
SUMMARY.txt, state.json, rate_*.log, train_*.log.
"""
