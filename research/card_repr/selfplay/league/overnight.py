STATE = {'train': None, 'rate': None, 'stop': False}


def kill(p):
    if p is None or p.poll() is not None:
        return
    try:
        os.killpg(p.pid, signal.SIGTERM)
        p.wait(timeout=30)
    except Exception:
        try:
            os.killpg(p.pid, signal.SIGKILL)
        except Exception:
            pass


def run(a):
    P = paths(a)
    log = Log(P['log'])
    deadline = parse_deadline(a.deadline)
    stop_train = deadline - a.final_rate_min * 60
    log(f'=== overnight.py start; deadline {time.ctime(deadline)}; training stops {time.ctime(stop_train)}; '
        f'args {vars(a)}')

    def on_sig(sig, frm):
        log(f'signal {sig}: stopping')
        STATE['stop'] = True
        kill(STATE['train']); kill(STATE['rate'])
    signal.signal(signal.SIGTERM, on_sig)
    signal.signal(signal.SIGINT, on_sig)

    setup(a, P, log)
    st = jload(P['state'], {'phase_no': 0, 'last_rate_t': 0, 'rated': [], 'fails': 0})
    rate_p = None
    rate_member = None
    st['last_rate_t'] = time.time() - a.rate_every_min * 60 + a.first_rate_min * 60

    # baseline / start rating right away (cf_B2 = the main agent at update 0)
    if not any(r['member'] == BASE_B2 for r in read_csv(P['tl'])):
        rate_p = STATE['rate'] = start_rating(a, P, log, BASE_B2); rate_member = BASE_B2

    while not STATE['stop'] and time.time() < stop_train:
        try:
            # ---- rating job bookkeeping
            if rate_p is not None and rate_p.poll() is not None:
                log(f'rating cycle for {rate_member} finished rc={rate_p.returncode}')
                if rate_p.returncode != 0:
                    log('ERROR rating cycle failed; tail of rate.log:\n' + tail(os.path.join(P['out'], 'rate.log'), 15))
                rate_p = STATE['rate'] = None
            if rate_p is None and time.time() - st['last_rate_t'] >= a.rate_every_min * 60:
                m = newest_main_snapshot(P)
                if m and m not in st['rated']:
                    rate_p = STATE['rate'] = start_rating(a, P, log, m); rate_member = m
                    st['rated'].append(m); st['last_rate_t'] = time.time()
            # ---- resources
            ensure_ram(log, a.min_ram_mb)
            if disk_free_gb(SP) < a.min_disk_gb:
                log(f'WARN disk free {disk_free_gb(SP):.1f} GB < {a.min_disk_gb}; pruning harder')
                a.max_ckpts = max(8, a.max_ckpts // 2)
            prune(a, P, log)
            # ---- one training phase
            st['phase_no'] += 1
            which = 'main' if st['phase_no'] % 2 == 1 else 'exp'
            if which == 'exp':
                if run_latest_update(P['main_run']) <= 0:
                    log('no main latest.pt yet; skipping exploiter phase')
                    jsave(P['state'], st); continue
                copy_target(P, log)
            n_upd = a.main_updates if which == 'main' else a.exp_updates
            left = (stop_train - time.time()) / 60
            if left < 1.0:
                break
            rc, _ = train_phase(a, P, log, which, n_upd, min(left, a.phase_max_min), seed=1000 + st['phase_no'])
            st['fails'] = st['fails'] + 1 if rc != 0 else 0
            jsave(P['state'], st)
            if st['fails'] >= 3:
                log(f'ERROR {st["fails"]} failed phases in a row; sleeping 120 s before retrying')
                time.sleep(120)
        except Exception:
            log('ERROR in driver loop (continuing):\n' + traceback.format_exc())
            time.sleep(30)

    # ---- final rating of the newest main snapshot (bounded by the deadline), then the summary
    if not STATE['stop']:
        if rate_p is not None and rate_p.poll() is None:
            log(f'waiting for the running rating cycle ({rate_member})')
            while rate_p.poll() is None and time.time() < deadline - 60:
                time.sleep(10)
            kill(rate_p)
        m = newest_main_snapshot(P)
        if m and m not in st['rated'] and time.time() < deadline - 120:
            rate_p = STATE['rate'] = start_rating(a, P, log, m); st['rated'].append(m)
            while rate_p.poll() is None and time.time() < deadline - 60:
                time.sleep(10)
            if rate_p.poll() is None:
                log('final rating cycle cut at the deadline'); kill(rate_p)
    kill(STATE['train']); kill(STATE['rate'])
    jsave(P['state'], st)
    try:
        summary(a, P, log)
    except Exception:
        log('ERROR writing SUMMARY:\n' + traceback.format_exc())
    log('=== overnight.py done')


