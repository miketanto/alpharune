class Log:
    def __init__(self, path):
        self.path = path

    def __call__(self, *a):
        s = time.strftime('%Y-%m-%d %H:%M:%S ') + ' '.join(str(x) for x in a)
        print(s, flush=True)
        with open(self.path, 'a') as f:
            f.write(s + '\n')


def parse_deadline(hhmm):
    now = datetime.datetime.now()
    h, m = (int(x) for x in hhmm.split(':'))
    d = now.replace(hour=h, minute=m, second=0, microsecond=0)
    if d <= now:
        d += datetime.timedelta(days=1)
    return d.timestamp()


def mem_available_mb():
    for line in open('/proc/meminfo'):
        if line.startswith('MemAvailable:'):
            return int(line.split()[1]) // 1024
    return -1


def drop_caches(log):
    """Drop the WSL page cache as root (wsl.exe -u root via interop; sudo needs a password here)."""
    cmds = [['/mnt/c/Windows/System32/wsl.exe', '-u', 'root', '-e', 'sh', '-c',
             'sync; echo 1 > /proc/sys/vm/drop_caches'],
            ['sudo', '-n', 'sh', '-c', 'sync; echo 1 > /proc/sys/vm/drop_caches']]
    for c in cmds:
        try:
            r = subprocess.run(c, timeout=60, capture_output=True)
            if r.returncode == 0:
                return True
        except Exception:
            pass
    log('WARN could not drop the page cache')
    return False


def ensure_ram(log, need_mb=1024, wait_s=600):
    t0 = time.time()
    while True:
        m = mem_available_mb()
        if m >= need_mb or m < 0:
            return m
        log(f'RAM low: MemAvailable {m} MB < {need_mb}; dropping page cache')
        drop_caches(log)
        m = mem_available_mb()
        if m >= need_mb:
            log(f'RAM after drop: {m} MB')
            return m
        if time.time() - t0 > wait_s:
            log(f'WARN RAM still {m} MB after {wait_s}s; continuing anyway')
            return m
        time.sleep(30)


def disk_free_gb(path):
    st = os.statvfs(path)
    return st.f_bavail * st.f_frsize / 2**30


def read_csv(path):
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return list(csv.DictReader(f))


def append_csv(path, cols, row):
    new = not os.path.exists(path)
    with open(path, 'a', newline='') as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction='ignore')
        if new:
            w.writeheader()
        w.writerow(row)


def jload(path, default):
    try:
        return json.load(open(path))
    except Exception:
        return default


def jsave(path, obj):
    tmp = path + '.tmp'
    json.dump(obj, open(tmp, 'w'), indent=1)
    os.replace(tmp, path)


