struct GameSpec {
    std::string deck_a, deck_b, agent_a, agent_b;
    uint64_t seed = 0;
    std::string base(const std::string& p) const {
        auto s = p.substr(p.find_last_of('/') + 1);
        return s.substr(0, s.rfind('.'));
    }
};

uint64_t engineSeedOf(uint64_t s) {
    s &= 0x7FFFFFFFu;
    return s == 0 ? 1 : s;
}

uint64_t mix(uint64_t x) {
    x += 0x9E3779B97F4A7C15ull;
    x = (x ^ (x >> 30)) * 0xBF58476D1CE4E5B9ull;
    x = (x ^ (x >> 27)) * 0x94D049BB133111EBull;
    return x ^ (x >> 31);
}

// A fingerprint of the position (ids, cards, places, numbers): equal in a
// replay of the same game at the same decision.
uint64_t fingerprint(const GameState& s) {
    uint64_t h = 1469598103934665603ull;
    auto add = [&](uint64_t v) { h = (h ^ v) * 1099511628211ull; };
    add(s.decision_index);
    add(s.turn.turn_number);
    add(static_cast<uint64_t>(s.turn.phase));
    add(static_cast<uint64_t>(s.turn.turn_player));
    for (const auto& p : s.players) {
        add(p.score); add(p.xp); add(p.main_deck.size()); add(p.trash.size());
        for (auto c : p.hand) { add(c.raw()); if (s.objectExists(c)) add(s.getObject(c).card_def_id.raw()); }
        add(p.rune_pool.energy);
    }
    std::vector<std::pair<uint32_t, uint64_t>> objs;
    for (const auto& [id, o] : s.objects.onBoard()) {
        uint64_t v = o.card_def_id.raw();
        v = v * 31 + static_cast<uint64_t>(o.current_might + 100);
        v = v * 31 + static_cast<uint64_t>(o.damage_marked);
        v = v * 31 + (o.battlefieldId().has_value() ? o.battlefieldId()->raw() + 2 : 1);
        v = v * 31 + o.is_exhausted;
        objs.push_back({id.raw(), v});
    }
    std::sort(objs.begin(), objs.end());
    for (auto& [i, v] : objs) { add(i); add(v); }
    add(s.chain.items.size());
    return h;
}

std::string hex(uint64_t v) { char b[20]; std::snprintf(b, 20, "%016llx", (unsigned long long)v); return b; }

bool topLevel(PromptKind k) {
    return k == PromptKind::MainPhase || k == PromptKind::ChainPriority || k == PromptKind::ShowdownFocus;
}

const char* kindName(PromptKind k) {
    switch (k) {
        case PromptKind::MainPhase: return "main";
        case PromptKind::ChainPriority: return "priority";
        case PromptKind::ShowdownFocus: return "focus";
        default: return "other";
    }
}

// ─── Probing one situation ────────────────────────────────────────────────
std::vector<double> runS(const GameState& st0, PlayerId me, GameObjectId self, bool last,
                         const std::function<void(GameEngine&)>& act, bool* error) {
    g_me = me;
    std::map<std::string, GameObjectId> roles;
    if (self.valid()) roles["SELF"] = self;
    EventBus events;
    ProbeAgent mine(last), other(false);
    EventCounter ec;
    std::vector<double> before, after;
    try {
        GameEngine e(*g_db, events, *g_reg);
        e.mutableState() = st0;
        if (me == P1) e.testHook_setAgents(&mine, &other);
        else e.testHook_setAgents(&other, &mine);
        e.testHook_cleanup();
        before = stateFeatures(e.state(), roles);
        ec.live = &e.state();
        ec.connect(events);
        act(e);
        ec.disconnect();
        after = stateFeatures(e.state(), roles);
    } catch (const std::exception& ex) {
        ec.disconnect();
        *error = true;
        g_error_log.push_back(std::string("S: ") + ex.what());
        ++g_errors;
        if (before.empty()) before = stateFeatures(st0, roles);
        after = before;
        ec.c.back() = 1;
    }
    std::vector<double> d(before.size());
    for (size_t i = 0; i < d.size(); ++i) d[i] = after[i] - before[i];
    ec.c[kEventFeat.size() - 2] = mine.prompts;
    d.insert(d.end(), ec.c.begin(), ec.c.end());
    g_me = P1;
    return d;
}

std::string sparse(const std::vector<std::string>& names, const std::vector<double>& v) {
    std::string o = "{";
    bool f = true;
    for (size_t i = 0; i < v.size() && i < names.size(); ++i) {
        if (v[i] == 0) continue;
        o += (f ? "" : ",") + jstr(names[i]) + ":" + jnum(v[i]);
        f = false;
    }
    return o + "}";
}

struct Candidate {
    std::string card;          // subject name
    uint32_t class_id = 0;
    std::string kind;          // play / act / held / trigger / inplay
    GameState st;
    std::vector<Intent> legal;
    PlayerId decider = PlayerId::None;
    PlayerId me = PlayerId::None;   // whose card (perspective of the record)
    GameObjectId self = kInvalidId;
    int decision = 0;
    std::string prompt;
    bool sub = false;
    GameObjectId host = kInvalidId;
    uint32_t host_card = 0;
    uint64_t fp = 0;
    int bfslot = 0;
};

// The probe of a candidate: legality + executed deltas. Returns the record line.
std::string probeCandidate(Candidate& c, const std::string& sid) {
    const auto dn = deltaNames();
    std::ostringstream o;
    o << "{\"sid\":" << jstr(sid) << ",\"card\":" << jstr(c.card) << ",\"kind\":" << jstr(c.kind)
      << ",\"sub\":" << (c.sub ? 1 : 0);
    bool err = false;
    if (c.kind == "inplay") {
        auto v = inPlayLegality(c.st, c.legal, c.self, c.bfslot);
        o << ",\"legal\":" << sparse(kInPlayNames, v) << "}";
        return o.str();
    }
    if (c.kind == "trigger") {
        o << ",\"exec\":{";
        bool first = true;
        for (bool last : {false, true}) {
            auto with = runS(c.st, c.me, c.self, last, [](GameEngine& e) { settle(e); }, &err);
            GameState without = c.st;
            without.chain.items.pop_back();
            if (without.chain.items.empty()) without.turn.oc_state = OpenClosedState::Open;
            auto base = runS(without, c.me, c.self, last, [](GameEngine& e) { settle(e); }, &err);
            std::vector<double> d(with.size());
            for (size_t k = 0; k < d.size(); ++k) d[k] = with[k] - base[k];
            d.back() = with.back();
            // the item itself is on the chain only in `with`: not an effect
            for (size_t k = 0; k < dn.size(); ++k) if (dn[k] == "chain_size") d[k] = 0;
            o << (first ? "" : ",") << "\"resolve/" << (last ? "last" : "first") << "\":" << sparse(dn, d);
            first = false;
        }
        o << "},\"err\":" << (err ? 1 : 0) << "}";
        return o.str();
    }
    // play / act / held: legality from the decider's legal list.
    std::vector<std::vector<Intent>> by_slot(kSlots.size());
    for (const auto& i : c.legal) {
        int s = slotOf(i, c.self);
        if (s >= 0) by_slot[s].push_back(i);
    }
    std::vector<double> lv;
    for (auto& v : by_slot) lv.push_back(double(v.size()));
    o << ",\"legal\":" << sparse(kSlots, lv) << ",\"exec\":{";
    bool first = true;
    std::vector<double> passed[2];
    for (size_t s = 0; s < kSlots.size(); ++s) {
        if (by_slot[s].empty()) continue;
        for (bool last : {false, true}) {
            if (passed[last].empty())
                passed[last] = runS(c.st, c.me, c.self, last, [](GameEngine& e) { settle(e); }, &err);
            const Intent pick = last ? by_slot[s].back() : by_slot[s].front();
            auto played = runS(c.st, c.me, c.self, last, [&](GameEngine& e) {
                e.testHook_executeIntent(pick);
                settle(e);
            }, &err);
            std::vector<double> d(played.size());
            for (size_t k = 0; k < d.size(); ++k) d[k] = played[k] - passed[last][k];
            d.back() = played.back();
            o << (first ? "" : ",") << jstr(kSlots[s] + (last ? "/last" : "/first")) << ":" << sparse(dn, d);
            first = false;
        }
    }
    o << "},\"err\":" << (err ? 1 : 0) << "}";
    return o.str();
}

// ─── Watching a game ───────────────────────────────────────────────────────
struct Subjects {
    std::map<uint32_t, std::string> by_id;   // class id -> subject name (first class of a key)
    std::set<uint32_t> in_decks;
};

class Watcher {
public:
    Watcher(const Subjects& subj, const GameSpec& g, std::ostream* index, std::ostream* records,
            int verify_decision = -1)
        : subj_(subj), g_(g), index_(index), records_(records), verify_decision_(verify_decision),
          rng_(mix(g.seed)) {}

    // Reservoir per key (card|kind|turn|seat): keep one candidate.
    void offer(Candidate&& c, const std::string& key) {
        auto& r = res_[key];
        ++r.first;
        std::uniform_int_distribution<long> u(0, r.first - 1);
        if (u(rng_) == 0) r.second = std::move(c);
    }

    void onDecision(const GameState& state, const std::vector<Intent>& legal, const Prompt& prompt) {
        if (verify_decision_ >= 0) {
            if (state.decision_index == verify_decision_) { verified_fp_ = fingerprint(state); throw StopGame(); }
            return;
        }
        if (!topLevel(prompt.kind) || state.chain.resuming.has_value()) return;
        if (state.turn.turn_number != turn_) { flush(); turn_ = state.turn.turn_number; }
        const PlayerId dec = prompt.decider != PlayerId::None ? prompt.decider : decidingPlayer(state, legal);
        const uint64_t fp = fingerprint(state);
        auto base = [&](const std::string& card, uint32_t cid, const std::string& kind) {
            Candidate c;
            c.card = card; c.class_id = cid; c.kind = kind;
            c.st = state; c.legal = legal; c.decider = dec; c.me = dec;
            c.decision = state.decision_index; c.prompt = kindName(prompt.kind); c.fp = fp;
            return c;
        };
        const std::string tk = "|" + std::to_string(state.turn.turn_number) + "|" + std::to_string(int(dec));
        // held / inplay change slowly: one per three turns
        const std::string tk3 = "|t" + std::to_string(state.turn.turn_number / 3) + "|" + std::to_string(int(dec));
        // play / act
        std::set<std::pair<uint32_t, std::string>> seen;
        for (const auto& i : legal) {
            GameObjectId obj = kInvalidId;
            std::string kind;
            const int ps = i.card.valid() ? slotOf(i, i.card) : -1;
            if (ps >= 0 && ps < 5) { obj = i.card; kind = "play"; }
            if (i.ability_source.valid() && slotOf(i, i.ability_source) == 5) { obj = i.ability_source; kind = "act"; }
            if (!obj.valid() || !state.objectExists(obj)) continue;
            const uint32_t cid = state.getObject(obj).card_def_id.raw();
            auto it = subj_.by_id.find(cid);
            if (it == subj_.by_id.end() || !seen.insert({cid, kind}).second) continue;
            Candidate c = base(it->second, cid, kind);
            c.self = obj;
            offer(std::move(c), it->second + "|" + kind + tk);
        }
        // held: in the decider's hand, nothing offered for it
        for (auto h : state.player(dec).hand) {
            if (!state.objectExists(h)) continue;
            const uint32_t cid = state.getObject(h).card_def_id.raw();
            auto it = subj_.by_id.find(cid);
            if (it == subj_.by_id.end() || seen.count({cid, "play"}) || seen.count({cid, "held"})) continue;
            bool offered = false;
            for (const auto& i : legal) if (slotOf(i, h) >= 0) offered = true;
            if (offered) continue;
            seen.insert({cid, "held"});
            Candidate c = base(it->second, cid, "held");
            c.self = h;
            offer(std::move(c), it->second + "|held" + tk3);
        }
        // trigger: top of the chain is a finalized triggered ability of a subject
        if (!state.chain.items.empty()) {
            const auto& top = state.chain.items.back();
            if (top.is_ability && !top.is_activated_ability && !top.keyword_ability.has_value() &&
                top.status == ChainItemStatus::Finalized) {
                auto it = subj_.by_id.find(top.card_def_id.raw());
                if (it != subj_.by_id.end()) {
                    Candidate c = base(it->second, top.card_def_id.raw(), "trigger");
                    c.self = top.source;
                    c.me = top.controller;
                    offer(std::move(c), it->second + "|trigger|" + std::to_string(state.turn.turn_number) +
                                            "|" + std::to_string(int(top.controller)));
                }
            }
        }
        // inplay: the decider's main phase, its permanents (and every battlefield card)
        if (prompt.kind == PromptKind::MainPhase) {
            std::vector<std::pair<GameObjectId, int>> perms;
            for (const auto& [id, o] : state.objects.inPlay())
                if (o.controller == dec && o.card_type != CardType::Battlefield) perms.push_back({id, 0});
            for (const auto& b : state.battlefields)
                if (state.objectExists(b.card_object_id)) perms.push_back({b.card_object_id, int(b.id.raw())});
            for (auto [id, slot] : perms) {
                const auto& o = state.getObject(id);
                auto it = subj_.by_id.find(o.card_def_id.raw());
                if (it == subj_.by_id.end()) continue;
                if (o.card_type == CardType::Rune) continue;
                Candidate c = base(it->second, o.card_def_id.raw(), "inplay");
                c.self = id;
                c.bfslot = slot;
                offer(std::move(c), it->second + "|inplay" + tk3 + "|" + std::to_string(slot));
            }
        }
        // substitution hosts: the decider has cards in hand
        const auto& hand = state.player(dec).hand;
        if (!hand.empty()) {
            for (const auto& [cid, name] : subj_.by_id) {
                if (subj_.in_decks.count(cid)) continue;
                // one host per (subject, turn, seat) for about one turn in three
                const uint64_t h = mix(g_.seed * 1000003ull + cid * 7919ull + state.turn.turn_number * 31ull + int(dec));
                if (h % 3 != 0) continue;
                Candidate c = base(name, cid, "sub");
                c.sub = true;
                c.host = hand[mix(h) % hand.size()];
                c.host_card = state.getObject(c.host).card_def_id.raw();
                offer(std::move(c), name + "|sub" + tk);
            }
        }
    }

    void flush() {
        for (auto& [key, r] : res_) emit(r.second);
        res_.clear();
    }

    void emit(Candidate& c) {
        if (c.kind == "sub") {
            // Substitute: the host hand card becomes the subject card.
            auto& o = c.st.getObject(c.host);
            const auto& def = g_db->get(CardDefId::fromRaw(c.class_id));
            o.card_def_id = def.id;
            o.name = def.name;
            o.card_type = def.card_type;
            o.super_type = def.super_type;
            o.keywords = def.keywords;
            o.domains = def.domains;
            o.tags = def.tags;
            o.base_might = def.might;
            o.current_might = def.might;
            o.assault_value = def.assault_value;
            o.shield_value = def.shield_value;
            o.deflect_value = def.deflect_value;
            o.might_bonus = def.might_bonus;
            c.self = c.host;
            c.legal.clear();
            try {
                EventBus events;
                ProbeAgent a1(false), a2(false);
                GameEngine e(*g_db, events, *g_reg);
                e.mutableState() = c.st;
                e.testHook_setAgents(&a1, &a2);
                e.testHook_cleanup();
                c.legal = e.generateLegalActions();
            } catch (const std::exception& ex) {
                g_error_log.push_back(std::string("S sub legality: ") + ex.what());
                ++g_errors;
            }
            bool offered = false;
            for (const auto& i : c.legal) if (slotOf(i, c.self) >= 0) offered = true;
            c.kind = offered ? "play" : "held";
        }
        const std::string sid = g_.base(g_.deck_a) + "-" + g_.base(g_.deck_b) + "-" + g_.agent_a + "-" + g_.agent_b +
                                "-s" + std::to_string(g_.seed) + "-d" + std::to_string(c.decision) + "-" + c.card +
                                "-" + c.kind + (c.sub ? "-sub" : "");
        *index_ << "{\"sid\":" << jstr(sid) << ",\"deck_a\":" << jstr(g_.deck_a) << ",\"deck_b\":" << jstr(g_.deck_b)
                << ",\"agent_a\":" << jstr(g_.agent_a) << ",\"agent_b\":" << jstr(g_.agent_b)
                << ",\"game_seed\":" << g_.seed << ",\"decision\":" << c.decision
                << ",\"turn\":" << c.st.turn.turn_number << ",\"prompt\":" << jstr(c.prompt)
                << ",\"decider\":" << int(c.decider) << ",\"card\":" << jstr(c.card) << ",\"class_id\":" << c.class_id
                << ",\"kind\":" << jstr(c.kind) << ",\"self_obj\":" << c.self.raw() << ",\"sub\":" << (c.sub ? 1 : 0)
                << ",\"host_obj\":" << (c.sub ? int(c.host.raw()) : -1) << ",\"host_card\":" << c.host_card
                << ",\"fp\":" << jstr(hex(c.fp)) << "}\n";
        *records_ << probeCandidate(c, sid) << "\n";
        ++emitted;
    }

    struct StopGame : std::runtime_error { StopGame() : std::runtime_error("stop") {} };
    long emitted = 0;
    uint64_t verified_fp_ = 0;

private:
    const Subjects& subj_;
    GameSpec g_;
    std::ostream* index_;
    std::ostream* records_;
    int verify_decision_;
    std::mt19937_64 rng_;
    int turn_ = -1;
    std::map<std::string, std::pair<long, Candidate>> res_;
};

class Seat : public AgentInterface {
public:
    Seat(std::unique_ptr<AgentInterface> inner, Watcher& w) : inner_(std::move(inner)), w_(w) {}
    Intent selectAction(const GameState& s, const std::vector<Intent>& legal) override {
        return inner_->selectAction(s, legal);
    }
    Intent decide(const GameState& s, const std::vector<Intent>& legal, const Prompt& p) override {
        w_.onDecision(s, legal, p);
        if (s.decision_index > 20000) throw std::runtime_error("decision cap");
        return inner_->decide(s, legal, p);
    }
private:
    std::unique_ptr<AgentInterface> inner_;
    Watcher& w_;
};

std::unique_ptr<AgentInterface> makeAgent(const std::string& spec, const GameSpec& g, uint64_t engine_seed, int seat) {
    const uint64_t derived = engine_seed * 2 + seat;
    double pass = 0;
    if (spec == "random") return std::make_unique<RandomAgent>(derived);
    if (isRandomPlayerSpec(spec, &pass)) return std::make_unique<RandomPlayerAgent>(derived, pass);
    if (spec.rfind("ismcts:sims=", 0) == 0) {
        const int sims = std::stoi(spec.substr(12));
        return std::make_unique<IsMctsAgent>(g.deck_a, g.deck_b, "", engine_seed, derived, sims);
    }
    throw std::invalid_argument("unknown agent " + spec);
}

std::vector<GameSpec> readGames(const std::string& path) {
    std::vector<GameSpec> out;
    std::ifstream in(path);
    GameSpec g;
    while (in >> g.deck_a >> g.deck_b >> g.agent_a >> g.agent_b >> g.seed) out.push_back(g);
    return out;
}

struct GameRun { std::string termination; int decisions = 0; double secs = 0; };

GameRun playOne(const GameSpec& g, const Subjects& subj, Watcher& w) {
    const auto t0 = std::chrono::steady_clock::now();
    GameRun r;
    const uint64_t es = engineSeedOf(g.seed);
    const DeckSubmission a = DeckValidator::loadFromDeckList(g.deck_a, *g_db);
    const DeckSubmission b = DeckValidator::loadFromDeckList(g.deck_b, *g_db);
    Seat s1(makeAgent(g.agent_a, g, es, 0), w), s2(makeAgent(g.agent_b, g, es, 1), w);
    EventBus events;
    GameEngine engine(*g_db, events, *g_reg);
    try {
        const GameResult res = engine.runGame(a, b, s1, s2, es);
        r.termination = res.termination_reason;
        r.decisions = res.total_decisions;
    } catch (const Watcher::StopGame&) {
        r.termination = "stopped";
    } catch (const std::exception& ex) {
        r.termination = std::string("error: ") + ex.what();
    }
    (void)subj;
    r.secs = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
    return r;
}

