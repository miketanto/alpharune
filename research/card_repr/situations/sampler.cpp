// sampler.cpp -- pool S of research/card_repr (PHASE2.md section 2/3):
// situations sampled from real games, and the card probes run in them.
//
// It plays real games of fixed deck lists with the engine's agents (fixed
// seeds), watches every top-level decision (main phase, chain priority,
// showdown focus; never one inside a resolution) and keeps, per (card, kind,
// turn, player) -- per three turns for held / inplay -- one decision at which
// a card of the subject list
//   play    : is offered to be played / hidden (a legal intent of the decider),
//   act     : has an activated ability offered,
//   trigger : has a triggered ability of its own on top of the chain (finalized),
//   inplay  : is in play (unit, gear, legend, battlefield) at its player's main phase,
//   held    : is in the decider's hand but no play is offered (legality only).
// The decision is picked by reservoir sampling inside the turn (seeded by
// the game seed), so the pick is a function of the seeds.
//
// Cards that are not in the two decks (the partners, the sideboard-only
// cards, the synthetic variants and the Hush stand-in) are substituted: at a
// host decision (the decider's top-level decision with cards in hand) one
// card of the decider's hand, chosen from the seeds, becomes the subject
// card; legality is regenerated by a fresh engine and the probe run there.
//
// A situation is identified by (deck A, deck B, agent A, agent B, game seed,
// decision index [, subject, substituted hand object]) and replays: the game
// is a function of its seeds (fuzz_game.h), and `verify` replays games to
// the recorded decision and checks a state fingerprint.
//
// Usage:
//   situation_sampler play <games.txt> <subjects.txt> <index_out.jsonl> <records_out.jsonl> [shard nshards]
//     games.txt lines: <deck A path> <deck B path> <agent A> <agent B> <game seed>
//     subjects.txt lines: <name> <class id> <rename 0|1> (C_engine/out/subjects.txt; renames skipped)
//   situation_sampler verify <games.txt> <index.jsonl> <max games>

